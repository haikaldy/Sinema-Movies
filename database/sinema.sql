  `seats` varchar(100) DEFAULT NULL,
  `snacks` varchar(100) DEFAULT NULL,
  `total` double DEFAULT NULL,
  `columnstatus` varchar(30) DEFAULT 'PAID',
  `booked_at` timestamp NOT NULL DEFAULT current_timestamp(),
  PRIMARY KEY (`booking_id`),
  KEY `user_id` (`user_id`),
  KEY `showtime_id` (`showtime_id`),
  CONSTRAINT `bookings_ibfk_1` FOREIGN KEY (`user_id`) REFERENCES `users` (`user_id`),
  CONSTRAINT `bookings_ibfk_2` FOREIGN KEY (`showtime_id`) REFERENCES `showtimes` (`showtime_id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci;

CREATE TABLE `seats` (
  `seat_id` int(11) NOT NULL AUTO_INCREMENT,
  `showtime_id` int(11) NOT NULL,
  `seat_number` varchar(5) NOT NULL,
  `status` varchar(15) NOT NULL,
  `booking_id` int(11) DEFAULT NULL,
  PRIMARY KEY (`seat_id`),
  UNIQUE KEY `uq_showtime_seat` (`showtime_id`,`seat_number`),
  KEY `showtime_id` (`showtime_id`),
  KEY `fk_seat_booking` (`booking_id`),
  CONSTRAINT `fk_seat_booking` FOREIGN KEY (`booking_id`) REFERENCES `bookings` (`booking_id`) ON DELETE SET NULL,
  CONSTRAINT `fk_seat_showtime` FOREIGN KEY (`showtime_id`) REFERENCES `showtimes` (`showtime_id`) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci;

CREATE TABLE `booking_seats` (
  `booking_seat_id` int(11) NOT NULL AUTO_INCREMENT,
